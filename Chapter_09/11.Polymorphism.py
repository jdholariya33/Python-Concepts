# Polymorphism : - Many forms

# Operator Overloading : - When the same operator is allowed to have different meaning according to the context.

# Example : many forms of the '+' operator

# Data type :- Integer
print(1 + 2)    # Output :- 3   -->     Addition

# Data type :- String
print("Jay" + "Dholariya")  # Output :- JayDholariya    -->     Concatenate

# Data type :- List
print([1, 2, 3] + [4, 5, 6])    # Output :- [1, 2, 3, 4, 5, 6]  -->     Merge

# This called Implicit Overloading