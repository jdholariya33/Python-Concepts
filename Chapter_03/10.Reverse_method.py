# 6. reverse() : - This method is used to reverse the elements of the list.

list = [20, 70, 10, 50, 30, 40] # List of integers

print("List before reverse : ", list)
list.reverse() # Reversing the list
print("List after reverse : ", list)


print(list.reverse()) # Reversing the list
print("List after reverse : ", list)