# Indexing in List : - Indexing starts from 0.

marks = [95.3, 85.5, 75.2, 65.1, 55.0] # List of float values

print("Mark at index 0 : ", marks[0]) # 95.3
print("Mark at index 1 : ", marks[1]) # 85.5
print("Mark at index -1 : ", marks[-1]) # 55.0
print("Mark at index -2 : ", marks[-2]) # 65.1

Teacher = ["Mr. Sharma", 35, 50000, "Mathematics"] # List of different data types

print("Teacher details : ", Teacher)
print("Name : ", Teacher[0]) # Mr. Sharma
print("Age : ", Teacher[1]) # 35
print("Salary : ", Teacher[2]) # 50000
print("Subject : ", Teacher[-1]) # Mathematics