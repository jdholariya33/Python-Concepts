# Basic Methods (Functions) in List

list = [20, 70, 10, 50, 30, 40] # List of integers

# 1. append() : - This method is used to add an element at the end of the list.

print("List before append : ", list)
list.append(60) # Adding element 60 at the end of the list
print("List after append : ", list)

print(list.append(80)) # Adding element 80 at the end of the list
print("List after append : ", list)


