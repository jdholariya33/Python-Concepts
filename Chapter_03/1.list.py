# List : - A built-in Data type that stores set of values.
#           It can store elements of different data types.(int, float, string, etc.)

marks = [90, 80, 70, 60, 50] # List of integers 
print("List of marks : ", marks)
print("Type of marks : ", type(marks)) # <class 'list'>
print("Length of marks : ", len(marks)) # 5


student = ["Karan", 20, 5.9, True] # List of different data types

print("Student details : ", student)
print("Type of student : ", type(student)) # <class 'list'>
print("Length of student : ", len(student)) # 4
