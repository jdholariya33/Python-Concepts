# Tuple Methods :

# 1. index(element) : - return index of first occurrence

tup = (15, 90, 3, 49, 18, 20, 3, 25, 77, 45, 3)

print(tup)
print("Index of 3:", tup.index(3))
print("Index of 18:", tup.index(18))


# 2. count(element) : - Counts total occurrences

print(tup)
print("Count of 3:", tup.count(3))
print("Count of 77:", tup.count(77))

