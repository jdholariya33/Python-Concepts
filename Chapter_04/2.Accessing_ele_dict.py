# Accessing Elements in dictionary :

info = {
    "name" : "meet",
    "age" : 20,
    "CGPA" : 7.58,
    "marks" : [78, 81, 70, 75, 88],
    "Male" : True
}

print("Information of the student : ", info)

print("Name of the student : ", info["name"])
print("Age of the student : ", info["age"])
print("Marks of the student : ", info["marks"])

