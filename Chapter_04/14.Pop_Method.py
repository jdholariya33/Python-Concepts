# 4. Pop Method : - The pop() method removes a random element from the set and returns it.

set1 = {"Python", "Language", "Friend", "Computer", "Programming"}

print("Original Set : ", set1)

print("Length of Original Set : ", len(set1))

print("Element removed from the set : ", set1.pop())    # It will remove a random element from the set.
print("Set after pop() method : ", set1)
