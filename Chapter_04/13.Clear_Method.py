# Clear Method : - Empties the set.

set1 = {10, 49, 25, 33, 77, 18}

print("Original Set : ", set1)
print("Length of Original Set : ", len(set1))

set1.clear()    # It will remove all the elements from the set.
print("Set after clear() method : ", set1)

print("Length of Set after clear() method : ", len(set1))