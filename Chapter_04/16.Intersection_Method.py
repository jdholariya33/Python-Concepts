# 6. Intersection Method : - The intersection() method Combines Common values and returns a new set.

set1 = {10, 49, 25, 33, 77, 18}
set2 = {100, 49, 200, 33, 77, 18, 200, 300}

set3 = set1.intersection(set2)

print("Set 1 : ", set1)
print("Set 2 : ", set2)
print("Intersection of Set 1 and Set 2 : ", set3)
