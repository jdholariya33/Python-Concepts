# 3. Assignment Operators (=, +=, -=, *=, /=, //=, %=, **=)

A = 30
A += 10     # Addition Assignment               # Output : - 40  
print(A)
A = 30
A -= 10     # Substraction Assignment           # Output : - 20
print(A)
A = 30
A *= 10     # Multiplication Assignment         # Output : - 300
print(A)
A = 30
A /= 10     # Division Assignment               # Output : - 3.0 
print(A)
A = 30
A //= 10    # Floor Division Assignment         # Output : - 3
print(A)
A = 30
A %= 10     # Modulus (Reminder) Assignment     # Output : - 0
print(A)
A = 30
A **= 10    # Exponentiation Assignment         # Output : - 590490000000000
print(A)
A = 30      

