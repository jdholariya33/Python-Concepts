# Operators :- Is a Specific symbol or keyword used to perform computations and logic operations on variables and values (Operands).
# Difine : - An Operator is a symbol that performs a certain operation between operands.

# 1. Arithmatic Operators :- (+ - * /  // % **)

A = 20
B = 10
print(A + B)    # Addition              # Output : - 30
print(A - B)    # Subtraction           # Output : - 10
print(A * B)    # Multiplication        # Output : - 200
print(A / B)    # Division              # Output : - 2.0
print(A // B)   # Integer Division      # Output : - 2
print(A % B)    # Modulo                # Output : - 0
print(A ** B)   # Exponentiation        # Output : - 10240000000000


