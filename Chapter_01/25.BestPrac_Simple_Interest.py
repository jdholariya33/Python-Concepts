# Best Practice - Simple Interest

# Formula : - SI = (P * R * T) / 100
# Where, SI = Simple Interest, P = Principal Amount, R = Rate of Interest, T = Time Period

p = float(input("Principal Amount (P) : "))
r = float(input("Rate of Interest (R) : "))
t = float(input("Time Period (T) : "))
si = (p * r * t) / 100
print("Simple Interest (SI) :", si)