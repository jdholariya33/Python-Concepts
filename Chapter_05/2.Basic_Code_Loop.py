# Basic Code in While Loop

# 1. Print Number From 1 to 5

i = 1

while i <= 5:
    print(i)
    i += 1


# 2. Print Number from 10 to 5 (Reverse)

i = 10

while i >= 5:
    print(i)
    i -= 1


# 3. print any one Pattern

i = 1

while i <= 5:
    print("* " * i)
    i += 1

