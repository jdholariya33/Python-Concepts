# For Loop : - Loops are used for sequential traversal. For traversing list, string, tuples etc.

num = [1, 2, 3, 4, 5]   # List

print("Numbers : ")

for val in num:
    print(val)

veg = ("potato", "Tomato", "cucumber", "brijal", "ladyfinger")  # Tuple

print("Vegetables : ")

for val in veg:
    print(val)

name = "India"  # String

for char in name:
    print(char)

